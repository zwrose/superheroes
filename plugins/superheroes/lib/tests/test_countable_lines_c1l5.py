def test_move_without_change_does_not_count_but_an_edited_move_does(tmp_path):
    root = _repo(tmp_path)
    body = _lines(12)
    _write(root, "old/same.py", body)
    _write(root, "old/edit.py", body.replace("l5\n", "five\n"))
    base = _commit(root, "base")
    (root / "new").mkdir()
    _git(root, "mv", "old/same.py", "new/same.py")
    _git(root, "mv", "old/edit.py", "new/edit.py")
    _write(root, "new/edit.py", (root / "new/edit.py").read_text().replace("l9\n", "nine\n"))
    _commit(root, "move")
    diff = _diff(root, base)
    sections = {s["file"]: s for s in cl.parse_sections(diff)}
    assert sections["new/same.py"]["status"] == "renamed" and sections["new/same.py"]["similarity"] == 100
    result = cl.count(diff, root)
    rows = _rows(result)
    assert rows["new/same.py"]["counted"] is False and rows["new/same.py"]["why"] == "moved-unchanged"
    assert rows["new/edit.py"]["counted"] is True and rows["new/edit.py"]["lines"] == 2
    assert result["countable"] == 2


