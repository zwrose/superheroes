def test_generated_files_do_not_count(tmp_path):
    root = _repo(tmp_path)
    _write(root, ".gitattributes", "by_attr.txt linguist-generated\nunset_attr.txt -linguist-generated\n")
    base = _commit(root, "base")
    _write(root, "by_attr.txt", "a\nb\nc\n")
