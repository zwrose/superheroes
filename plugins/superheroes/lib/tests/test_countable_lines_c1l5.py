def test_a_deleted_section_pairs_with_at_most_one_added_section():
    body = "".join("+l%d\n" % i for i in range(1, 4))
    gone = "".join("-l%d\n" % i for i in range(1, 4))
    diff = (
        "diff --git a/old.py b/old.py\ndeleted file mode 100644\n--- a/old.py\n+++ /dev/null\n@@ -1,3 +0,0 @@\n" + gone
        + "diff --git a/one.py b/one.py\nnew file mode 100644\n--- /dev/null\n+++ b/one.py\n@@ -0,0 +1,3 @@\n" + body
        + "diff --git a/two.py b/two.py\nnew file mode 100644\n--- /dev/null\n+++ b/two.py\n@@ -0,0 +1,3 @@\n" + body
    )
    rows = _rows(cl.count(diff, "/nonexistent-root"))
    assert rows["one.py"]["why"] == "moved-unchanged"
    # The second copy is unpaired, so it reaches the generated test, which cannot run in a missing repo.
    assert rows["two.py"]["why"] == "unsettled"


