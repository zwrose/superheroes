_PINNED_ENV = {**os.environ, "GIT_CONFIG_GLOBAL": os.devnull, "GIT_CONFIG_NOSYSTEM": "1"}
_IDENTITY = ["-c", "user.name=Fixture", "-c", "user.email=fixture@example.invalid"]
# Built from pieces: the counter's own rule would read a literal marker near the top of this file.
GEN_TAG = "@" + "generated"
GO_MARK = "// Code generated by fixture. DO NOT" + " EDIT."


@pytest.fixture(autouse=True)
def _pin_git_for_the_module(monkeypatch, tmp_path):
    monkeypatch.setenv("GIT_CONFIG_GLOBAL", os.devnull)
    monkeypatch.setenv("GIT_CONFIG_NOSYSTEM", "1")
    monkeypatch.setenv("GIT_CEILING_DIRECTORIES", str(tmp_path))


def _git(root, *args):
    proc = subprocess.run(
        ["git", "-C", str(root), *_IDENTITY, *args],
        env=_PINNED_ENV, capture_output=True, text=True, check=True,
    )
    return proc.stdout


def _repo(tmp_path, name="repo"):
    root = tmp_path / name
    root.mkdir()
    subprocess.run(["git", "init", "-q", "-b", "main", str(root)], env=_PINNED_ENV, check=True, capture_output=True)
    return root


def _write(root, rel, text):
    path = root / rel
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
    return path


def _commit(root, message):
    _git(root, "add", "-A")
    _git(root, "commit", "-q", "-m", message)
    return _git(root, "rev-parse", "HEAD").strip()


def _diff(root, base, *extra):
    return _git(root, "-c", "core.quotePath=false", "diff", *extra, base + "...HEAD")


def _rows(result):
    return {row["file"]: row for row in result["files"]}


def _lines(n, prefix="l"):
    return "".join("%s%d\n" % (prefix, i) for i in range(1, n + 1))


def _sha(data):
    return hashlib.sha256(data).hexdigest()


