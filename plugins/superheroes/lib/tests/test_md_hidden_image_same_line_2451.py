"""#2451: ``md_hidden._inline_pass`` no longer adds the sticky unsure point "image description that may span lines" for a
``![`` whose description provably closes on its own line.

The invariant: that point is not added for a ``![`` whose first ``]`` lies before the next newline and whose text between
holds none of ``[``, a backtick, ``<`` or a backslash; it is still added, exactly as before, for every other ``![`` the
old condition fires on. The rule only removes a firing the old condition made; it never adds one.

The oracle: the orchestrator rendered each body below with cmark-gfm ``0.29.0.gfm.13`` (the ``cmarkgfm`` package, the
renderer version GitHub's vet 854 corpus agrees with) and read the HTML with a spec HTML5 parser. Each test's docstring
states the recorded reading; this file runs no renderer. Fake runners only: no real gh, no network.

Guard tests are named ``test_eN_*`` (N = 1..6; E1 the call-site exemption, E2 ``[``, E3 ``<``, E4 backtick, E5
backslash, E6 the line-break check); the bite-proof record is ``bite_proofs/i2451_md_hidden_image_same_line.md``."""
import pytest

import md_hidden
import vet_slot as vs
from test_vet_slot import SLOT, FakeGh, _comment, _pages
from test_vet_slot_no_build_record_2342 import BOT_BODY, RECEIPT_NONE

PR = 42
REPO = "owner/example"
REASON = "image description that may span lines"
V, H = md_hidden.VISIBLE, md_hidden.HIDDEN

_ROWS = "".join(
    "| [example-pkg-%s](https://example.invalid/pkg/%s) | [`1.0.%d` -> `1.1.0`](https://example.invalid/diff/%d) | "
    "[![age](https://example.invalid/badge/age/%d.svg)](https://example.invalid/docs) | "
    "[![confidence](https://example.invalid/badge/confidence/%d.svg)](https://example.invalid/docs) |\n"
    % (c, c, i, i, i, i) for i, c in enumerate("abcde"))
RENOVATE_BODY = ("This PR contains the following updates:\n\n| Package | Change | Age | Confidence |\n|---|---|---|---|\n"
                 + _ROWS + "\n---\n\n### Release Notes\n\n<details>\n<summary>example-pkg-a</summary>\n\n- a fix\n\n"
                 "</details>\n\n---\n\n### Configuration\n\nThis PR was generated by a dependency bot.\n")

CONTROL_BODY = "![a](https://example.invalid/x.png) text\nmore ] text\n\n<!-- ZQ1 -->\n\n## ZQ2\n"
E2_BODY = "![a [b][r" + "`]`]]" + "\nZQ1](https://example.invalid/x.png)\n\n[r`]: /v\n"
E2_VET_BODY = "![a [b](c]d)\nZQ1](https://example.invalid/x.png)\n\n" + BOT_BODY
E3_BODY = "![a <!-- ---> ] -->\nZQ1](https://example.invalid/x.png)\n\n## ZQ2\n"
E4_BODY = "![a " + "`]`" + " b\nZQ1](https://example.invalid/x.png)\n\n## ZQ2\n"
E5_BODY = "![a \\] b\nZQ1](https://example.invalid/x.png)\n\n## ZQ2\n"
E6_BODY = "![a\nZQ1](https://example.invalid/x.png)\n\n## ZQ2\n"


@pytest.fixture(autouse=True)
def _gh_on_path(monkeypatch):
    monkeypatch.setattr(vs.shutil, "which", lambda name: "/usr/bin/gh" if name == "gh" else None)


def _state_of_line_holding(body, needle):
    """The state ``md_hidden.scan`` gives the line that holds ``needle`` (``state_at`` takes a line-start offset)."""
    return md_hidden.scan(body).state_at(body.rindex("\n", 0, body.index(needle)) + 1)


def _reasons(body):
    return [why for _at, why in md_hidden.scan(body).unsure]


def _evaluate(body):
    return vs.evaluate("write", body, [_comment(RECEIPT_NONE)], SLOT, advisor_login="advisor")


def test_e1_renovate_shaped_body_holds_no_image_span_point_and_its_last_heading_is_visible():
    """Oracle (cmark-gfm 0.29.0.gfm.13): every ``![...]`` in the table closes on its own line and ``### Configuration``
    is a visible heading. The point is not added and the heading line reads VISIBLE."""
    assert REASON not in _reasons(RENOVATE_BODY)
    assert _state_of_line_holding(RENOVATE_BODY, "### Configuration") == V


def test_e1_renovate_shaped_body_writes_through_evaluate_and_run_verb(tmp_path):
    """The same body: ``evaluate("write")`` returns ok (base: ``write-failed``, the marker line read unsure), and
    ``run_verb("write")`` with a FakeGh makes exactly one edit."""
    assert _evaluate(RENOVATE_BODY)["ok"] is True
    fake = FakeGh([RENOVATE_BODY], _pages([_comment(RECEIPT_NONE)]))
    path = tmp_path / "slot.md"
    path.write_text(SLOT, encoding="utf-8")
    result = vs.run_verb("write", PR, REPO, slot_file=str(path), run=fake)
    assert result["ok"] is True, result
    assert len(fake.edit_calls()) == 1


def test_e1_control_removing_the_point_reveals_each_lines_own_state():
    """Oracle: ``<!-- ZQ1 -->`` is a comment (hidden), ``## ZQ2`` is visible. The first ``]`` closes the image on its
    line, so no point is held and each line reads its own state, the hidden one included."""
    assert REASON not in _reasons(CONTROL_BODY)
    assert _state_of_line_holding(CONTROL_BODY, "ZQ1") == H
    assert _state_of_line_holding(CONTROL_BODY, "ZQ2") == V


def test_e2_open_bracket_in_the_description_keeps_the_point():
    """Oracle: ZQ1 sits in the image's alt text (hidden). The description holds ``[``, so the point stays and the ZQ1
    line is not VISIBLE."""
    assert _state_of_line_holding(E2_BODY, "ZQ1") != V
    assert REASON in _reasons(E2_BODY)


def test_e2_a_truly_spanning_description_still_refuses_write_failed():
    """Oracle: ZQ1 is in the alt (hidden). The vet-slot write of a body holding it refuses."""
    result = _evaluate(E2_VET_BODY)
    assert result["ok"] is False and result["reason"] == "write-failed", result


def test_e3_angle_bracket_in_the_description_keeps_the_point():
    """Oracle: ZQ1 is hidden. The description holds ``<``, so the point stays and the ZQ1 line is not VISIBLE."""
    assert _state_of_line_holding(E3_BODY, "ZQ1") != V
    assert REASON in _reasons(E3_BODY)


def test_e4_backtick_in_the_description_keeps_the_point():
    """Oracle: ZQ1 is hidden. The description holds backticks, so the ZQ1 line is not VISIBLE. (Also held today by the
    "possible link metadata spans lines" rule; the bite-proof pairs this element with that rule neutralized.)"""
    assert "\\" not in E4_BODY
    assert _state_of_line_holding(E4_BODY, "ZQ1") != V


def test_e5_backslash_in_the_description_keeps_the_point():
    """Oracle: ZQ1 is hidden. The description holds one backslash before ``]``, so the ZQ1 line is not VISIBLE."""
    assert E5_BODY.count("\\") == 1
    assert _state_of_line_holding(E5_BODY, "ZQ1") != V


def test_e6_first_closer_on_a_later_line_keeps_the_point():
    """Oracle: ZQ1 is hidden. The first ``]`` is on a later line, so the ZQ1 line is not VISIBLE."""
    assert _state_of_line_holding(E6_BODY, "ZQ1") != V


@pytest.mark.parametrize("text, at, expected", [
    ("![age](u)\nx ]", 0, True),
    ("![](u)\n]", 0, True),
    ("![https://example.invalid/a]b\n]", 0, True),  # ":" is not refused
    ("![abc", 0, False),  # F1: no "]" at all
    ("![a\nb]", 0, False),  # F2: the first "]" is on a later line
    ("![a [b]", 0, False),  # F3: "[" in the description
    ("![a `x]", 0, False),  # F4: backtick
    ("![a <x]", 0, False),  # F5: "<"
    ("![a \\]", 0, False),  # F6: backslash
])
def test_helper_description_closes_on_its_line(text, at, expected):
    assert md_hidden._description_closes_on_its_line(text, at) is expected
